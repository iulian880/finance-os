/// <summary>
/// Applies the real control styles and templates (M2). Guards against silently dropped setters,
/// missing template parts and hard-coded colors that would not follow the theme.
/// </summary>
[Collection(WpfCollection.Name)]
public sealed class ControlStyleTests
{
    public static TheoryData<Type> ImplicitlyStyledTypes =>
    [
        typeof(Button), typeof(TextBox), typeof(ComboBox), typeof(ComboBoxItem), typeof(CheckBox),
        typeof(DatePicker), typeof(DatePickerTextBox), typeof(Calendar), typeof(ToolTip), typeof(ScrollBar),
        typeof(TimePicker), typeof(Badge),
    ];

    [Theory]
    [MemberData(nameof(ImplicitlyStyledTypes))]
    public void Every_base_control_has_an_implicit_style(Type type)
    {
        RunOnSta(() =>
        {
            var style = Assert.IsType<Style>(LoadDesignSystem()[type]);
            Assert.True(style.TargetType.IsAssignableFrom(type));
        });
    }

    [Theory]
    [InlineData("Button.Primary")]
    [InlineData("Button.Secondary")]
    [InlineData("Button.Ghost")]
    [InlineData("Button.Danger")]
    [InlineData("Button.Icon")]
    [InlineData("TextBox.Multiline")]
    [InlineData("Toggle")]
    public void Named_variants_exist(string key)
    {
        RunOnSta(() => Assert.IsType<Style>(LoadDesignSystem()[key]));
    }

    [Theory]
    [InlineData(null, "Surface", "TextPrimary", false)]
    [InlineData("Button.Primary", "Accent", "OnAccent", false)]
    [InlineData("Button.Secondary", "Surface", "TextPrimary", false)]
    [InlineData("Button.Danger", "DangerFillRest", "OnDanger", false)]
    [InlineData("Button.Primary", "Accent", "OnAccent", true)]
    [InlineData("Button.Danger", "DangerFillRest", "OnDanger", true)]
    public void Button_variants_use_theme_colors(string? styleKey, string background, string foreground, bool dark)
    {
        RunOnSta(() =>
        {
            var button = new Button { Content = "OK" };
            Host(button, dark);
            if (styleKey is not null)
            {
                button.Style = (Style)button.FindResource(styleKey);
                Layout(button);
            }

            Assert.Equal(Token(dark, background), ColorOf(button.Background));
            Assert.Equal(Token(dark, foreground), ColorOf(button.Foreground));
            Assert.Equal(14.0, button.FontSize);
            Assert.Contains("Inter", button.FontFamily.Source, StringComparison.Ordinal);
        });
    }

    [Theory]
    [InlineData("Button.Primary")]
    [InlineData("Button.Secondary")]
    [InlineData("Button.Ghost")]
    [InlineData("Button.Danger")]
    public void Disabled_buttons_use_tertiary_text(string styleKey)
    {
        RunOnSta(() =>
        {
            var button = new Button { Content = "OK", IsEnabled = false };
            Host(button);
            button.Style = (Style)button.FindResource(styleKey);
            Layout(button);

            Assert.Equal(Token(false, "TextTertiary"), ColorOf(button.Foreground));
        });
    }

    [Fact]
    public void Controls_follow_a_runtime_theme_swap()
    {
        RunOnSta(() =>
        {
            var button = new Button { Content = "OK" };
            var root = Host(button, dark: false);
            Assert.Equal(Token(false, "Surface"), ColorOf(button.Background));

            SwapTheme(root, dark: true);
            Assert.Equal(Token(true, "Surface"), ColorOf(button.Background));
        });
    }

    [Fact]
    public void Templates_provide_the_parts_wpf_requires()
    {
        RunOnSta(() =>
        {
            var text = new TextBox();
            var combo = new ComboBox { ItemsSource = new[] { "A", "B" } };
            var date = new DatePicker();
            var time = new TimePicker();
            var calendar = new Calendar { DisplayDate = new DateTime(2026, 11, 4) };
            var panel = new StackPanel { Children = { text, combo, date, time, calendar } };
            Host(panel);

            Part<ScrollViewer>(text, "PART_ContentHost");
            Part<Popup>(combo, "PART_Popup");
            Part<DatePickerTextBox>(date, "PART_TextBox");
            Part<Button>(date, "PART_Button");
            Part<Popup>(date, "PART_Popup");
            Part<TextBox>(time, TimePicker.PartTextBox);
            Part<Popup>(time, TimePicker.PartPopup);
            Part<ListBox>(time, TimePicker.PartList);

            // Month view: 7 weekday titles + 42 day cells, all generated by WPF into our grid.
            var item = Part<CalendarItem>(calendar, "PART_CalendarItem");
            var month = Part<Grid>(item, "PART_MonthView");
            Assert.Equal(49, month.Children.Count);
            Assert.Equal(42, month.Children.OfType<CalendarDayButton>().Count());
            Part<Button>(item, "PART_HeaderButton");
        });
    }

    [Fact]
    public void Calendar_switches_to_the_year_view()
    {
        RunOnSta(() =>
        {
            var calendar = new Calendar();
            Host(calendar);
            var item = Part<CalendarItem>(calendar, "PART_CalendarItem");

            calendar.DisplayMode = CalendarMode.Year;
            Layout(calendar);

            Assert.Equal(Visibility.Hidden, Part<Grid>(item, "PART_MonthView").Visibility);
            Assert.Equal(Visibility.Visible, Part<Grid>(item, "PART_YearView").Visibility);
        });
    }

    [Fact]
    public void Placeholder_shows_only_while_the_field_is_empty()
    {
        RunOnSta(() =>
        {
            var text = new TextBox();
            FieldAssist.SetPlaceholder(text, "Ex.: BT");
            Host(text);
            var placeholder = Part<TextBlock>(text, "Placeholder");
            Assert.Equal(Visibility.Visible, placeholder.Visibility);
            Assert.Equal("Ex.: BT", placeholder.Text);

            text.Text = "Reconciliere";
            Layout(text);
            Assert.Equal(Visibility.Collapsed, placeholder.Visibility);
        });
    }

    [Fact]
    public void Error_text_replaces_helper_text_and_marks_the_field()
    {
        RunOnSta(() =>
        {
            var text = new TextBox();
            FieldAssist.SetHeader(text, "Sumă");
            FieldAssist.SetHelperText(text, "În lei");
            Host(text);
            Assert.Equal(Visibility.Visible, Part<TextBlock>(text, "Helper").Visibility);
            Assert.Equal(Visibility.Collapsed, Part<TextBlock>(text, "Error").Visibility);

            FieldAssist.SetErrorText(text, "Sumă invalidă");
            Layout(text);
            Assert.True(FieldAssist.GetHasError(text));
            Assert.Equal(Visibility.Collapsed, Part<TextBlock>(text, "Helper").Visibility);
            Assert.Equal(Visibility.Visible, Part<TextBlock>(text, "Error").Visibility);
            Assert.Equal(Token(false, "Danger"), ColorOf(Part<Border>(text, "Chrome").BorderBrush));
        });
    }

    [Fact]
    public void Header_and_messages_reach_automation()
    {
        RunOnSta(() =>
        {
            var text = new TextBox();
            FieldAssist.SetHeader(text, "Titlu");
            FieldAssist.SetHelperText(text, "Scurt și clar");
            Assert.Equal("Titlu", AutomationProperties.GetName(text));
            Assert.Equal("Scurt și clar", AutomationProperties.GetHelpText(text));

            FieldAssist.SetErrorText(text, "Obligatoriu");
            Assert.Equal("Obligatoriu", AutomationProperties.GetHelpText(text));

            FieldAssist.SetErrorText(text, null);
            Assert.False(FieldAssist.GetHasError(text));
            Assert.Equal("Scurt și clar", AutomationProperties.GetHelpText(text));

            // A header change follows through, but an explicit, different name is respected.
            FieldAssist.SetHeader(text, "Titlu task");
            Assert.Equal("Titlu task", AutomationProperties.GetName(text));
            AutomationProperties.SetName(text, "Titlul taskului curent");
            FieldAssist.SetHeader(text, "Altceva");
            Assert.Equal("Titlul taskului curent", AutomationProperties.GetName(text));
        });
    }

