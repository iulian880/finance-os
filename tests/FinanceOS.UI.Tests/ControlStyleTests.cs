    [Fact]
    public void Interactive_controls_show_a_keyboard_focus_indicator()
    {
        RunOnSta(() =>
        {
            var button = new Button();
            var check = new CheckBox();
            var toggle = new CheckBox();
            var panel = new StackPanel { Children = { button, check, toggle } };
            Host(panel);
            toggle.Style = (Style)toggle.FindResource("Toggle");
