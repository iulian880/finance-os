    [Fact]
    public void Text_field_and_select_start_their_text_at_the_same_inset()
    {
        // Fields stacked in a form must line up. WPF's text box also applies Padding inside its
        // content host, so a template that adds Padding as a margin as well indents text twice.
        RunOnSta(() =>
        {
            var text = new TextBox { Text = "C:\\Data", IsReadOnly = true };
            var combo = new ComboBox { ItemsSource = new[] { "Luminos" }, SelectedIndex = 0 };
            var panel = new StackPanel { Width = 300, Children = { text, combo } };
            Host(panel);

            var textLeft = text.GetRectFromCharacterIndex(0).Left;
            var site = Descendants<ContentPresenter>(combo).First(p => p.Content is "Luminos");
            var comboLeft = site.TranslatePoint(new Point(0, 0), combo).X;

            Assert.InRange(textLeft, comboLeft - 1, comboLeft + 1);
        });
    }

    [Fact]
    public void Chrome_toggle_follows_its_state_after_clicks()
    {
        // The title-bar toggles bind IsChecked OneWay and change state through a command. A click must
        // not replace the binding with a local value, or the button stops following the panel.
        RunOnSta(() =>
        {
            var state = new PanelState();
            var toggle = new ToggleButton { DataContext = state, Command = state.Toggle };
            toggle.SetBinding(ToggleButton.IsCheckedProperty, new System.Windows.Data.Binding(nameof(PanelState.IsOpen)) { Mode = System.Windows.Data.BindingMode.OneWay });
            Host(toggle);
            toggle.Style = (Style)toggle.FindResource("ToggleButton.Chrome");
            Layout(toggle);
            var background = ColorOf(toggle.Background);

            Click(toggle);
            Assert.True(state.IsOpen);
            Assert.True(toggle.IsChecked);
            Assert.NotEqual(background, ColorOf(toggle.Background));

            state.IsOpen = false; // closed elsewhere (e.g. the panel's own close button)
            Assert.False(toggle.IsChecked);

            Click(toggle);
            Click(toggle);
            Assert.False(state.IsOpen);
            Assert.False(toggle.IsChecked);

            state.IsOpen = true;
            Assert.True(toggle.IsChecked);
        });
    }

    private static void Click(ButtonBase button) =>
        typeof(ButtonBase).GetMethod("OnClick", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)!
            .Invoke(button, null);

    private sealed class PanelState : System.ComponentModel.INotifyPropertyChanged
    {
        private bool _isOpen;

        public PanelState() => Toggle = new DelegateCommand(() => IsOpen = !IsOpen);

        public event System.ComponentModel.PropertyChangedEventHandler? PropertyChanged;

        public System.Windows.Input.ICommand Toggle { get; }

        public bool IsOpen
        {
            get => _isOpen;
            set
            {
                _isOpen = value;
                PropertyChanged?.Invoke(this, new(nameof(IsOpen)));
            }
        }
    }

    private sealed class DelegateCommand(Action execute) : System.Windows.Input.ICommand
    {
        public event EventHandler? CanExecuteChanged
        {
            add { }
            remove { }
        }

        public bool CanExecute(object? parameter) => true;

        public void Execute(object? parameter) => execute();
    }

    private static IEnumerable<T> Descendants<T>(DependencyObject root)
        where T : DependencyObject
    {
        for (var i = 0; i < System.Windows.Media.VisualTreeHelper.GetChildrenCount(root); i++)
        {
            var child = System.Windows.Media.VisualTreeHelper.GetChild(root, i);
            if (child is T match)
            {
                yield return match;
            }

            foreach (var nested in Descendants<T>(child))
            {
                yield return nested;
            }
        }
    }
}
